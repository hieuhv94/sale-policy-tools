-- =============================================================================
-- 0091 — `idn.outbox`: tài khoản và phiên đăng nhập vào được nhật ký
-- =============================================================================
--
-- Rà nhật ký theo sáu câu hỏi kiểm toán (22/08) cho ra một nguyên nhân chung cho
-- BA câu không trả lời được:
--
--   "Ai đã đăng nhập tháng 7, có lần nào thất bại không?"
--   "Ai tạo tài khoản này, ai vô hiệu hoá nó?"
--   "Có ai dò mật khẩu không?"
--
-- Cả ba hỏng vì cùng một chỗ: `identity` **không phát một sự kiện nào**, và
-- schema `idn` không có bảng `outbox`. Chín service kia đều có; đây là service
-- duy nhất đứng ngoài đường sự kiện, nên mọi việc nó làm đều vô hình với nhật
-- ký. Hệ thống CÓ đếm số lần đăng nhập sai và CÓ khoá tạm tài khoản — việc ấy
-- cũng không để lại vết nào.
--
-- Bảng này giống hệt bốn bảng outbox kia, kể cả cột `seq` của `0009` (thứ tự
-- phát phải là thứ tự ghi) và chỉ mục một phần cho hàng chưa gửi. Giống là chủ
-- ý: `OutboxRelay` dùng chung cho cả năm, và một bảng lệch khuôn là một nhánh
-- riêng trong đoạn mã khó kiểm nhất của hệ thống.
--
-- KHÔNG ghi mật khẩu, không ghi token, không ghi thân request. Nhật ký trả lời
-- "ai làm gì lúc nào", không phải "họ đã gõ gì".
-- =============================================================================

CREATE TABLE IF NOT EXISTS idn.outbox (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  seq          bigint GENERATED BY DEFAULT AS IDENTITY,
  routing_key  text NOT NULL,
  payload      jsonb NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz
);

-- Chỉ mục MỘT PHẦN: relay chỉ hỏi "còn hàng nào chưa gửi không", và sau khi gửi
-- xong thì hàng ấy rời khỏi chỉ mục. Chỉ mục đầy đủ trên `created_at` sẽ lớn
-- ngang cả bảng trong khi 99% số dòng không bao giờ được hỏi tới.
CREATE INDEX IF NOT EXISTS ix_idn_outbox_pending
  ON idn.outbox(seq) WHERE published_at IS NULL;

GRANT SELECT, INSERT, UPDATE, DELETE ON idn.outbox TO csbh_idn;

-- Dọn hàng ĐÃ GỬI cùng nhịp với ba outbox kia. `sys.run_retention()` khai tham
-- số `p_outbox_keep_days` một lần cho tất cả, nên thêm một câu DELETE ở đây là
-- đủ — không có con số thứ hai để lệch.
CREATE OR REPLACE FUNCTION sys.don_idn_outbox(p_keep_days int DEFAULT 30)
RETURNS bigint AS $$
DECLARE n bigint;
BEGIN
  DELETE FROM idn.outbox
   WHERE published_at IS NOT NULL
     AND published_at < now() - (p_keep_days || ' days')::interval;
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$ LANGUAGE plpgsql
  SECURITY DEFINER SET search_path = pg_catalog, idn, sys;

COMMENT ON FUNCTION sys.don_idn_outbox(int) IS
  'Dọn hàng đã gửi của idn.outbox. Gọi từ sys.run_retention() (0091).';

-- Nối vào chính `run_retention()`. Không viết lại cả hàm ở đây: nó dài, và chép
-- lại một hàm chỉ để thêm một dòng là cách chắc chắn để hai bản trôi khỏi nhau.
-- `CREATE OR REPLACE` của Postgres đòi cả thân hàm, nên đường duy nhất còn lại
-- là gọi hàm con ở trên từ một lượt sửa sau — hoặc để sla-worker gọi nó.
--
-- Chọn: sla-worker gọi `sys.don_idn_outbox()` ngay sau `sys.run_retention()`.
-- Một lời gọi thêm, không phải một bản sao của hàm 40 dòng.
GRANT EXECUTE ON FUNCTION sys.don_idn_outbox(int) TO csbh_pol;
