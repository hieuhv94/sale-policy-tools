-- =============================================================================
-- 0009_outbox_order — Thứ tự sự kiện outbox phải TẤT ĐỊNH.
--
-- `created_at` mặc định `now()`, mà `now()` trong Postgres là thời điểm BẮT ĐẦU
-- TRANSACTION chứ không phải thời điểm chạy câu lệnh. Mọi sự kiện phát trong
-- cùng một transaction vì thế mang dấu thời gian GIỐNG HỆT nhau, và
-- `ORDER BY created_at` trả về thứ tự tuỳ ý.
--
-- Với publisher ở P6 thì đây không phải chuyện nhỏ: gửi `policy.publish_signed`
-- trước `policy.tbp_sign` là email tới kế toán trước email báo đã ký.
-- =============================================================================

ALTER TABLE cat.outbox ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE cus.outbox ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE pol.outbox ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY;

-- Publisher đọc theo seq và ghi nhớ vị trí đã gửi tới đâu.
CREATE INDEX IF NOT EXISTS ix_cat_outbox_seq ON cat.outbox (seq) WHERE published_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_cus_outbox_seq ON cus.outbox (seq) WHERE published_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_pol_outbox_seq ON pol.outbox (seq) WHERE published_at IS NULL;

COMMENT ON COLUMN pol.outbox.seq IS 'Thứ tự phát sự kiện — dùng thay created_at vì now() giống nhau trong cùng transaction';
