-- =============================================================================
-- 0011_document — Siêu dữ liệu file, chữ ký điện tử nội bộ (YCNV muc 10, 11.1).
--
-- File THẬT nằm trên MinIO. Bảng này giữ thứ MinIO không giữ được: băm SHA-256
-- để phát hiện file bị sửa ngoài đường ứng dụng, ai tải lên, thuộc hồ sơ nào, và
-- bản đã ký là bản ký TỪ file nào.
--
-- KHÔNG có bảng hợp đồng ở đây và sẽ không bao giờ có (muc 8.3): xuất hợp đồng
-- là một phép biến đổi trả PDF về thẳng người bấm, không phải một bản ghi.
-- =============================================================================

DO $$ BEGIN
  CREATE TYPE doc.file_purpose AS ENUM (
    'HO_SO',      -- file đính kèm hồ sơ CSBH do TDV tải lên
    'SCAN',       -- bản scan bản cứng đã ký, do Sale Admin tải lên
    'PHAP_LY',    -- hồ sơ pháp lý của khách hàng
    'BAN_CSBH',   -- bản CSBH A4 do hệ thống sinh
    'BAN_DA_KY',  -- bản CSBH A4 đã có chữ ký điện tử của Trưởng bộ phận
    'MAU_HD');    -- mẫu hợp đồng .docx do Sale Admin tải lên
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

DO $$ BEGIN
  CREATE TYPE doc.owner_kind AS ENUM ('POLICY', 'CUSTOMER', 'TEMPLATE');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

CREATE TABLE IF NOT EXISTS doc.stored_file (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  object_key   text UNIQUE NOT NULL,

  -- Tên người dùng thấy, giữ nguyên dấu tiếng Việt. Khoá object trên MinIO thì
  -- KHÔNG mang tên này (xem chú thích ở storage.ts) — tách đôi để tên hiển thị
  -- tuỳ ý còn khoá lưu trữ thì luôn an toàn (DOC-18).
  file_name    text NOT NULL,
  content_type text NOT NULL,
  size_bytes   bigint NOT NULL CHECK (size_bytes > 0),

  -- Băm tính lúc tải lên, đối chiếu lại lúc tải về. Không có nó thì "file trên
  -- MinIO bị sửa" là chuyện không cách nào phát hiện (DOC-06).
  sha256       text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),

  owner_kind   doc.owner_kind NOT NULL,
  owner_id     uuid,
  purpose      doc.file_purpose NOT NULL,

  -- Bản đã ký trỏ về bản nháp. Hai object khác nhau, bản nháp KHÔNG bị ghi đè:
  -- "trước và sau khi ký" phải đối chiếu được (DOC-05).
  signed_from_id uuid REFERENCES doc.stored_file(id),

  -- Chữ ký điện tử NỘI BỘ: họ tên, vai trò, dấu thời gian. Không chứng thư số,
  -- không HSM, không CA — cố ý (DOC-07).
  signature    jsonb,

  uploaded_by  uuid NOT NULL,
  uploaded_at  timestamptz NOT NULL DEFAULT now(),

  -- Xoá thật khỏi MinIO thì đánh dấu ở đây, giữ lại VẾT chứ không giữ file.
  deleted_at   timestamptz,
  delete_reason text
);

CREATE INDEX IF NOT EXISTS ix_stored_file_owner
  ON doc.stored_file(owner_kind, owner_id) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS ix_stored_file_purpose ON doc.stored_file(purpose);

CREATE TABLE IF NOT EXISTS doc.outbox (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  seq          bigint GENERATED BY DEFAULT AS IDENTITY,
  routing_key  text NOT NULL,
  payload      jsonb NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz
);
CREATE INDEX IF NOT EXISTS ix_doc_outbox_pending
  ON doc.outbox(seq) WHERE published_at IS NULL;

