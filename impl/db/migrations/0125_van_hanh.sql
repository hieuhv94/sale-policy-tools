-- `0252` — service `van-hanh` (service thứ 11, chặng B3 của trang Vận hành).
--
-- Role riêng `csbh_ops`, cùng khuôn chín role của `0002`: chỉ thấy schema `ops`. Sửa
-- được LỊCH (`cau_hinh_viec`) và ghi LƯỢT CHẠY (`lan_chay` — lượt nén log do chính
-- service này chạy). Không có quyền gì trên dữ liệu nghiệp vụ.
--
-- Mọi thao tác ghi (đổi lịch, xoá tệp log, xoá bản sao lưu) phát sự kiện qua
-- `ops.outbox` → nhật ký kiểm toán, cùng đường mười service kia (AD-03).

DO $$
DECLARE
  pwd text := coalesce(current_setting('csbh.role_password', true), 'csbh_dev_pw');
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'csbh_ops') THEN
    EXECUTE format('CREATE ROLE csbh_ops LOGIN PASSWORD %L', pwd);
  END IF;
END $$;

GRANT CONNECT ON DATABASE csbh TO csbh_ops;
GRANT USAGE ON SCHEMA ops TO csbh_ops;

CREATE TABLE IF NOT EXISTS ops.outbox (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  seq          bigint GENERATED BY DEFAULT AS IDENTITY,
  routing_key  text NOT NULL,
  payload      jsonb NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  published_at timestamptz
);
CREATE INDEX IF NOT EXISTS ix_ops_outbox_pending ON ops.outbox (seq) WHERE published_at IS NULL;

GRANT SELECT, UPDATE ON ops.cau_hinh_viec TO csbh_ops;
GRANT SELECT, INSERT, UPDATE ON ops.lan_chay TO csbh_ops;
GRANT SELECT, INSERT, UPDATE ON ops.outbox TO csbh_ops;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA ops TO csbh_ops;
GRANT EXECUTE ON FUNCTION ops.buoc(text), ops.moc_truoc(text, timestamptz),
                          ops.moc_ke_tiep(text, timestamptz), ops.den_han(text, timestamptz) TO csbh_ops;

-- `ops.outbox` cũ dần như mọi outbox khác — dọn cùng nhịp với `doc.outbox`.
CREATE OR REPLACE FUNCTION sys.don_ops_outbox(p_keep_days int DEFAULT 30) RETURNS bigint
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, ops AS $$
DECLARE n bigint;
BEGIN
  DELETE FROM ops.outbox
   WHERE published_at IS NOT NULL
     AND published_at < now() - (p_keep_days || ' days')::interval;
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n;
END $$;
REVOKE EXECUTE ON FUNCTION sys.don_ops_outbox(int) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION sys.don_ops_outbox(int) TO csbh_pol;
