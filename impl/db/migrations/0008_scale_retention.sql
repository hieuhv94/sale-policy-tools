-- =============================================================================
-- 0008_scale_retention — Yêu cầu phi chức năng: CSDL không phình vô hạn, tìm
-- kiếm không quét toàn bảng, nhật ký cắt được theo tháng.
--
-- Làm BÂY GIỜ vì phân vùng bảng nhật ký phải quyết định trước khi có dữ liệu
-- thật; chuyển một bảng vài trăm nghìn dòng đang chạy sang bảng phân vùng thì
-- phải dừng hệ thống.
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- --- Nhật ký: chuyển sang bảng PHÂN VÙNG THEO THÁNG --------------------------
--
-- Bất biến "chỉ ghi thêm" khiến bảng này KHÔNG dọn được bằng DELETE — đó là chủ
-- ý. Cách duy nhất còn lại để nó không phình vô hạn là phân vùng theo tháng rồi
-- DETACH vùng cũ đem lưu trữ: dữ liệu vẫn còn, chỉ không nằm trong bảng nóng nữa.
-- Hàm tạo vùng khai báo TRƯỚC, vì bước chuyển đổi bên dưới cần gọi nó.
CREATE OR REPLACE FUNCTION aud.ensure_partition(p_month date) RETURNS text AS $fn$
DECLARE
  start_at date := date_trunc('month', p_month)::date;
  end_at   date := (date_trunc('month', p_month) + interval '1 month')::date;
  name     text := 'audit_log_' || to_char(start_at, 'YYYY_MM');
BEGIN
  IF EXISTS (SELECT 1 FROM pg_class WHERE relname = name
               AND relnamespace = 'aud'::regnamespace) THEN
    RETURN name;
  END IF;
  EXECUTE format(
    'CREATE TABLE aud.%I PARTITION OF aud.audit_log FOR VALUES FROM (%L) TO (%L)',
    name, start_at, end_at);
  EXECUTE format('GRANT SELECT, INSERT ON aud.%I TO csbh_aud', name);
  RETURN name;
END $fn$ LANGUAGE plpgsql;

DO $$
DECLARE
  has_parts boolean;
  lo date;
  hi date;
  m  date;
BEGIN
  SELECT EXISTS (SELECT 1 FROM pg_partitioned_table pt WHERE pt.partrelid = 'aud.audit_log'::regclass)
    INTO has_parts;
  IF has_parts THEN RETURN; END IF;

  ALTER TABLE aud.audit_log RENAME TO audit_log_old;

  -- Khoá chính phải chứa cột phân vùng: Postgres không cho khoá duy nhất nào
  -- thiếu cột đó, vì nó không kiểm được tính duy nhất xuyên vùng.
  CREATE TABLE aud.audit_log (
    id           bigint GENERATED BY DEFAULT AS IDENTITY,
    occurred_at  timestamptz NOT NULL DEFAULT now(),
    actor_id     uuid,
    actor_role   text,
    actor_ip     inet,
    action       text NOT NULL,
    entity       text NOT NULL,
    entity_id    uuid,
    before_data  jsonb,
    after_data   jsonb,
    reason       text,
    trace_id     text,
    app_version  text,
    PRIMARY KEY (occurred_at, id)
  ) PARTITION BY RANGE (occurred_at);

  -- TẠO VÙNG TRƯỚC KHI CHÉP DỮ LIỆU.
  --
  -- Chép vào vùng mặc định rồi mới tạo vùng theo tháng thì Postgres từ chối:
  -- "updated partition constraint for default partition would be violated by
  -- some row" — dòng đã nằm ở vùng mặc định không tự chuyển sang vùng mới được.
  SELECT date_trunc('month', min(occurred_at))::date,
         date_trunc('month', max(occurred_at))::date
    INTO lo, hi FROM aud.audit_log_old;
  lo := least(coalesce(lo, current_date), date_trunc('month', current_date)::date);
  hi := greatest(coalesce(hi, current_date),
                 (date_trunc('month', current_date) + interval '3 months')::date);

  m := lo;
  WHILE m <= hi LOOP
    PERFORM aud.ensure_partition(m);
    m := (m + interval '1 month')::date;
  END LOOP;

  -- Vùng hứng mọi thứ ngoài các tháng đã tạo. Không có nó thì một dòng lệch
  -- ngày sẽ làm INSERT hỏng, và nhật ký hỏng là mất dấu vết chứ không chỉ mất
  -- một dòng. Bình thường vùng này phải RỖNG.
  CREATE TABLE aud.audit_log_default PARTITION OF aud.audit_log DEFAULT;

  INSERT INTO aud.audit_log
    (occurred_at, actor_id, actor_role, actor_ip, action, entity, entity_id,
     before_data, after_data, reason, trace_id, app_version)
  SELECT occurred_at, actor_id, actor_role, actor_ip, action, entity, entity_id,
         before_data, after_data, reason, trace_id, app_version
    FROM aud.audit_log_old;

  DROP TABLE aud.audit_log_old;
END $$;

-- Tháng này và ba tháng tới, để không bao giờ rơi vào vùng mặc định vì quên tạo.
DO $$
DECLARE i int;
BEGIN
  FOR i IN 0..3 LOOP
    PERFORM aud.ensure_partition((current_date + (i || ' months')::interval)::date);
  END LOOP;
END $$;

-- Trigger phải gắn lại trên bảng mới; bảng cha phân vùng nhận trigger cho cả vùng con.
DROP TRIGGER IF EXISTS trg_audit_immutable ON aud.audit_log;
CREATE TRIGGER trg_audit_immutable
  BEFORE UPDATE OR DELETE ON aud.audit_log
  FOR EACH ROW EXECUTE FUNCTION aud.forbid_mutation();

DROP TRIGGER IF EXISTS trg_audit_no_truncate ON aud.audit_log;
CREATE TRIGGER trg_audit_no_truncate
  BEFORE TRUNCATE ON aud.audit_log
  FOR EACH STATEMENT EXECUTE FUNCTION aud.forbid_mutation();

GRANT SELECT, INSERT ON aud.audit_log TO csbh_aud;
GRANT SELECT, INSERT ON aud.audit_log_default TO csbh_aud;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA aud TO csbh_aud;

-- Màn hình nhật ký lọc theo thời gian và theo đối tượng. Thiếu index thì mỗi lần
-- mở là quét toàn bộ lịch sử.
CREATE INDEX IF NOT EXISTS ix_audit_time   ON aud.audit_log (occurred_at DESC);
CREATE INDEX IF NOT EXISTS ix_audit_entity ON aud.audit_log (entity, entity_id, occurred_at DESC);

-- --- Index cho tìm kiếm và cho việc dọn dẹp ---------------------------------

-- ILIKE '%...%' không dùng được index B-tree — luôn quét toàn bảng. GIN + trigram
-- là cách duy nhất để tìm chuỗi con có index (CUST-17).
CREATE INDEX IF NOT EXISTS ix_customer_search
  ON cus.customer USING gin (
    (name || ' ' || registered_address || ' ' || coalesce(id_number, '')) gin_trgm_ops);

-- Dọn theo hạn thì phải có index theo hạn, nếu không chính việc dọn lại quét bảng.
CREATE INDEX IF NOT EXISTS ix_refresh_expiry    ON idn.refresh_token (expires_at);
CREATE INDEX IF NOT EXISTS ix_activation_expiry ON idn.activation_token (expires_at);
CREATE INDEX IF NOT EXISTS ix_cat_outbox_sent   ON cat.outbox (published_at) WHERE published_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_cus_outbox_sent   ON cus.outbox (published_at) WHERE published_at IS NOT NULL;
CREATE INDEX IF NOT EXISTS ix_pol_outbox_sent   ON pol.outbox (published_at) WHERE published_at IS NOT NULL;

-- sla-worker (P6) quét các hồ sơ quá hạn — không có index thì nó quét toàn bảng
-- hồ sơ mỗi lần chạy.
CREATE INDEX IF NOT EXISTS ix_policy_sla ON pol.policy (sla_due_at)
  WHERE sla_due_at IS NOT NULL;

-- --- Dọn dữ liệu hết vòng đời ------------------------------------------------
--
-- Bốn bảng dưới đây chỉ tăng nếu không ai dọn. Với 50 người dùng thì
-- idn.refresh_token một mình đã là ~150 nghìn dòng sau ba năm.
--
-- KHÔNG đụng tới aud.audit_log: nhật ký không được xoá, chỉ được tách vùng.
CREATE TABLE IF NOT EXISTS sys.retention_run (
  id         bigserial PRIMARY KEY,
  ran_at     timestamptz NOT NULL DEFAULT now(),
  detail     jsonb NOT NULL
);

CREATE OR REPLACE FUNCTION sys.run_retention(
  p_outbox_keep_days int DEFAULT 30,
  p_token_grace_days int DEFAULT 7
) RETURNS jsonb AS $$
DECLARE
  n_refresh int; n_activation int; n_cat int; n_cus int; n_pol int;
  detail jsonb;
BEGIN
  -- Token đã hết hạn từ lâu thì không còn giá trị điều tra nào.
  DELETE FROM idn.refresh_token
   WHERE expires_at < now() - (p_token_grace_days || ' days')::interval;
  GET DIAGNOSTICS n_refresh = ROW_COUNT;

  DELETE FROM idn.activation_token
   WHERE expires_at < now() - (p_token_grace_days || ' days')::interval;
  GET DIAGNOSTICS n_activation = ROW_COUNT;

  -- CHỈ xoá bản ĐÃ GỬI. Bản chưa gửi là việc còn nợ, xoá đi là mất sự kiện.
  DELETE FROM cat.outbox WHERE published_at IS NOT NULL
     AND published_at < now() - (p_outbox_keep_days || ' days')::interval;
  GET DIAGNOSTICS n_cat = ROW_COUNT;

  DELETE FROM cus.outbox WHERE published_at IS NOT NULL
     AND published_at < now() - (p_outbox_keep_days || ' days')::interval;
  GET DIAGNOSTICS n_cus = ROW_COUNT;

  DELETE FROM pol.outbox WHERE published_at IS NOT NULL
     AND published_at < now() - (p_outbox_keep_days || ' days')::interval;
  GET DIAGNOSTICS n_pol = ROW_COUNT;

  -- Luôn giữ sẵn vùng nhật ký cho ba tháng tới.
  PERFORM aud.ensure_partition((current_date + (i || ' months')::interval)::date)
     FROM generate_series(0, 3) AS i;

  detail := jsonb_build_object(
    'refreshToken', n_refresh, 'activationToken', n_activation,
    'catOutbox', n_cat, 'cusOutbox', n_cus, 'polOutbox', n_pol);
  INSERT INTO sys.retention_run (detail) VALUES (detail);
  RETURN detail;
END $$ LANGUAGE plpgsql;

COMMENT ON FUNCTION sys.run_retention IS
  'Dọn dữ liệu hết vòng đời. sla-worker gọi mỗi ngày; chạy tay bằng make retention';
